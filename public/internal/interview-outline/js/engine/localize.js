function applyReplacements(html){
  if(!html) return html;
  /* 1) 车型替换：单遍正则、长者优先（S11 类与 MPV 类词链不同） */
  if(state.repModel){
    const terms = (isMPVType()?MODEL_TERMS_MPV:MODEL_TERMS_S11).slice().sort((a,b)=>b.length-a.length);
    const rx = new RegExp(terms.map(escReg).join('|'),'g');
    html = html.replace(rx, ()=>state.repModel);
  } else if(!isMPVType()){
    /* 默认脱敏：未填写车型名时，车型指称统一泛化为「该车型」，避免项目代号/尺寸外露 */
    const terms = MODEL_TERMS_S11.slice().sort((a,b)=>b.length-a.length);
    const rx = new RegExp(terms.map(escReg).join('|'),'g');
    html = html.replace(rx, ()=>'该车型');
  }
  /* 2) 国家名称/城市/旗帜替换（普通字符串，安全无正则元字符问题） */
  repCountryPairs().forEach(([from,to])=>{ html = html.split(from).join(to); });
  /* 3) 代号替换（词边界匹配，避免误伤英文单词，如 docsub 的「HK/TH」） */
  Object.keys(state.repCountries).forEach(cc=>{
    const c = COUNTRIES.find(x=>x.code===cc);
    const r = state.repCountries[cc];
    if(!c||!r||!r.code||r.code===c.code) return;
    const rx = new RegExp('\\b'+escReg(c.code)+'\\b','g');
    html = html.replace(rx, ()=>r.code);
  });
  /* 4) 移除「（原模块X）」「（原B部分X）」等来源标注后缀 */
  html = html.replace(/（原[^）]*）/g, '');
  /* 清理可能残留的多余右括号 */
  html = html.replace(/）{2,}/g, '）');
  return html;
}

